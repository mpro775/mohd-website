export async function seedCertifications(
  certificationModel: Model<Certification>,
) {
  for (const data of certificationsData) {
    const {
      imageMediaId: _imageMediaId,
      documentMediaId: _documentMediaId,
      issuerLogoMediaId: _issuerLogoMediaId,
      expiresAt: _expiresAt,
      durationHours: _durationHours,
      seo,
      ...content
    } = data;

    // Use dot notation for SEO so a manually selected OG image is preserved.
    const $set = {
      ...content,
      'seo.metaTitle': seo.metaTitle,
      'seo.metaDescription': seo.metaDescription,
    };

    const existing = await certificationModel.findOne({ slug: data.slug });
    if (existing) {
      console.log(
        `Certification with slug "${data.slug}" already exists, updating content and preserving media...`,
      );
      await certificationModel.updateOne({ slug: data.slug }, { $set });
    } else {
      console.log(`Creating certification: ${data.title}`);
      await certificationModel.create({
        ...content,
        seo: {
          metaTitle: seo.metaTitle,
          metaDescription: seo.metaDescription,
        },
      });
    }
  }

  console.log('Certifications seeding completed successfully!');
}
